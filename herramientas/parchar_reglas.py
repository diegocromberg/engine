#!/usr/bin/env python3
"""
V35 - Pasa las reglas y el evento Start de GeneXus a los YAML existentes, SIN regenerarlos:

  reglas: |      las reglas de la TRN, en la sintaxis de GeneXus (con sus comentarios)
  inicio: |      el evento Start (Variables + código), que carga &Decimales, &Instalacion, etc.

- Lo que es del patrón WorkWithPlus (Insert_..., botones, clases, celdas) y lo que el motor ya resuelve
  de otra forma (Default, Serial, Prompt, NoAccept fijo) no se pasa.
- [win]{...} se descarta; [web]{...} se desenvuelve.
- Los dominios enumerados se reemplazan por su valor (Parametro.IvaTipo1 -> 16, TrnMode.Insert -> "INS").
- Agrega, ocultos, los atributos que usan las reglas y faltaban (como hace parchar_formulas.py).
- Traduce a proc/ los procedimientos que llaman las reglas y el inicio (y los que llaman esos), si no estaban.
- Saca del YAML el comentario "PENDIENTE" (las reglas pasan a 'reglas:').
- Una TRN que ya tiene 'reglas:' no se toca (salvo --pisar).

Las reglas que el motor no puede leer quedan comentadas con "// REVISAR:" (eso lo hace el paso de
validación: python3 parchar_reglas.py ... y después el chequeo de Java; ver GUIA, sección 17).

Uso:
  python3 parchar_reglas.py OptimistU12NEW.xml --trn ../src/main/resources/trn --proc ../src/main/resources/proc [--solo PRS] [--ver]
"""
import argparse, json, os, re, sys
import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gx2yaml as g
import gx2proc as gp
import parchar_formulas as pf

T_TRN = '1db606f2-af09-4cf9-a3b5-b481519d28f6'


# ----------------------------------------------------------------------------- lectura

def variables_trn(xml):
    """{Trn: [{nombre, props}]} de la KB (caché trn_vars_v1.json al lado del XML)."""
    cache = os.path.join(os.path.dirname(os.path.abspath(xml)), 'trn_vars_v1.json')
    if os.path.exists(cache) and os.path.getmtime(cache) >= os.path.getmtime(xml):
        return json.load(open(cache, encoding='utf-8'))
    import xml.etree.ElementTree as ET
    r, stack = {}, []
    for ev, el in ET.iterparse(xml, events=('start', 'end')):
        if ev == 'start':
            stack.append(el.tag)
            continue
        stack.pop()
        if len(stack) == 2 and el.tag == 'Object':
            if el.get('type') == T_TRN:
                for p in el.findall('Part'):
                    if (p.get('type') or '').startswith('e4c4ade7'):
                        r[el.get('name')] = [{'nombre': v.get('Name'),
                                              'props': {x.findtext('Name'): x.findtext('Value') for x in v.iter('Property')}}
                                             for v in p.findall('Variable')]
            el.clear()
    json.dump(r, open(cache, 'w', encoding='utf-8'))
    return r


# ----------------------------------------------------------------------------- texto de GeneXus

GEN = re.compile(r'/\*\s*Generated by DVelop Work With Plus Pattern \[Start\][^*]*\*/(.*?)/\*\s*Generated by DVelop Work With Plus Pattern \[End\][^*]*\*/', re.S)


def recorrer(t):
    """Posiciones que no están en textos ni comentarios (generador de índices 'de código')."""
    i, n, q = 0, len(t), None
    while i < n:
        c = t[i]
        if q:
            if c == q or c == '\n':
                q = None
            i += 1
            continue
        if c in '"\'':
            q = c
            i += 1
            continue
        if t.startswith('//', i):
            j = t.find('\n', i)
            i = n if j < 0 else j
            continue
        if t.startswith('/*', i):
            j = t.find('*/', i + 2)
            i = n if j < 0 else j + 2
            continue
        yield i
        i += 1


def bloques_plataforma(t):
    """[win]{...} fuera; [web]{...} -> su contenido. También '[web]' sin llaves (se saca la marca)."""
    for _ in range(200):
        m = re.search(r'\[(win|web|bc)\]\s*(?:(?://[^\n]*\n|/\*.*?\*/)\s*)*\{', t, re.I | re.S)
        if not m:
            break
        ini = m.end() - 1
        prof, fin = 0, None
        for i in recorrer(t):
            if i < ini:
                continue
            if t[i] == '{':
                prof += 1
            elif t[i] == '}':
                prof -= 1
                if prof == 0:
                    fin = i
                    break
        if fin is None:
            break
        dentro = t[ini + 1:fin]
        t = t[:m.start()] + ('' if m.group(1).lower() in ('win', 'bc') else dentro) + t[fin + 1:]
    t = re.sub(r'\[(web|win)\]', '', t, flags=re.I)
    # '[bc] regla;' sin llaves: solo vale para el business component
    t = re.sub(r'(?is)\[bc\][^;]*;', '', t)
    # llaves sueltas que quedaron (bloques mal cerrados en GeneXus): fuera, respetando textos y comentarios
    cod = set(recorrer(t))
    return ''.join(' ' if (i in cod and ch in '{}') else ch for i, ch in enumerate(t))


def sentencias(t):
    """Parte las reglas por ';' (fuera de textos, comentarios y paréntesis). Devuelve [(comentarios_previos, regla)]."""
    r, ini, prof = [], 0, 0
    for i in recorrer(t):
        c = t[i]
        if c == '(':
            prof += 1
        elif c == ')':
            prof -= 1
        elif c == ';' and prof <= 0:
            r.append(t[ini:i])
            ini, prof = i + 1, 0
    r.append(t[ini:])
    out = []
    for trozo in r:
        # comentarios de adelante (se conservan) + la regla (sin comentarios adentro, en un renglón)
        codigo = g.sin_comentarios(trozo)
        pos = next((i for i in recorrer(trozo)), len(trozo))
        # los comentarios que están antes de la primera letra de código
        primero = next((i for i in recorrer(trozo) if not trozo[i].isspace()), len(trozo))
        previos = trozo[:primero]
        regla = ' '.join(codigo.split())
        out.append((previos, regla))
    return out


def limpiar_comentarios(previos):
    """Comentarios de adelante, uno por renglón, sin sangría (vacíos colapsados)."""
    ls = [l.strip() for l in previos.split('\n')]
    r = []
    for l in ls:
        if not l:
            if r and r[-1] != '':
                r.append('')
            continue
        r.append(l)
    while r and r[0] == '':
        r.pop(0)
    while r and r[-1] == '':
        r.pop()
    return r


DESCARTAR = re.compile(r'(?i)^(default|serial|prompt|noprompt|error_handler|parm|refcall|refmsg|accept|order|subtype|equal|add|subtract|submit|call\s*\(\s*\'?Prompt)\s*\(')
CONTROL = re.compile(r'(?i)^([A-Za-z_]\w*)\s*\.\s*(class|caption|link|tooltiptext|rows|columns|backcolor|forecolor|jsevent|titleformat|visible|enabled|width|height|format|linktarget)\b')


def clasificar(regla, campos):
    """None = se descarta (lo resuelve el motor de otra forma o es del patrón); si no, la regla (texto)."""
    if not regla:
        return None
    if DESCARTAR.match(regla):
        return None
    m = CONTROL.match(regla)
    if m:
        # solo Enabled/Visible de atributos de la TRN; lo demás es de controles de la pantalla de GeneXus
        if m.group(2).lower() in ('enabled', 'visible') and m.group(1).lower() in campos:
            return regla
        return None
    if re.match(r'(?i)^noaccept\s*\(', regla) and not re.search(r'(?i)\bif\b', regla):
        return None   # NoAccept fijo: ya es soloLectura en el YAML
    if re.search(r'(?i)&Insert_\w+|&TrnContext|GridLevel_|_Cell\b|TextBlock\w*\.', regla):
        return None
    if re.match(r'(?i)^&\w+\s*\.\s*(link|fromimage|fromurl|forecolor|backcolor|visible|enabled|class|tooltiptext|caption|bitmap|jsevent)\b', regla):
        return None   # propiedades de controles de la pantalla de GeneXus (variables de imagen, links)
    return regla


def reglas_de(texto, campos, enums):
    t = texto.replace('\r\n', '\n')
    m = GEN.search(t)
    if m:
        # del bloque generado por WorkWithPlus solo quedan Visible/Enabled de atributos (ej. PRSComisionistaId.Visible = ...)
        extra = [regla for _, regla in sentencias(bloques_plataforma(m.group(1))) if clasificar(regla, campos) and CONTROL.match(regla)]
        t = t[:m.start()] + ''.join('\n' + x + ';' for x in extra) + '\n' + t[m.end():]
    t = bloques_plataforma(t)
    lineas = []
    for previos, regla in sentencias(t):
        com = limpiar_comentarios(previos)
        r = clasificar(regla, campos)
        if r is None:
            if com and not regla:
                lineas += com
            elif com:
                # el comentario de una regla que no se pasa no se pierde si es texto (no código)
                lineas += [c for c in com if not re.match(r'^/\*+\s*$|^\*+/$', c)]
            continue
        r = g.reemplazar_enums(r, enums)
        if lineas and lineas[-1] != '' and com:
            lineas.append('')
        lineas += com
        lineas.append(r + ';')
    # quitar comentarios que quedaron colgados al final y renglones vacíos repetidos
    while lineas and (lineas[-1] == '' or (lineas[-1].startswith(('/*', '//', '*')) and not any(not x.startswith(('/*', '//', '*')) and x for x in lineas))):
        lineas.pop()
    limpio = []
    for l in lineas:
        if l == '' and (not limpio or limpio[-1] == ''):
            continue
        limpio.append(l)
    return limpio


FOTOS = []   # variables Boolean que agrega el inicio (fotos de Visible/Enabled)
START = re.compile(r'(?is)\bEvent\s+Start\b(.*?)\bEndEvent\b')
INICIO_NO = re.compile(r'(?i)^\s*(?:[A-Za-z_]\w*\s*\.\s*(?!call\b|udp\b)\w+\s*[=(]|.*\bNotAuthorized\b|.*\bWebSession\b|.*\.FromXml\s*\(|.*&TrnContext|Do\s+[\'"]|.*\bGridLevel_)')
PROP_INICIO = re.compile(r'(?i)^\s*([A-Za-z_]\w*)\s*\.\s*(visible|enabled)\s*=\s*(.+?)\s*;?\s*$')


def inicio_de(eventos, enums, campos=frozenset(), a_reglas=None):
    """Líneas del evento Start. Los 'Atributo.Visible/Enabled = ...' de primer nivel (fuera de If/For) pasan a reglas."""
    m = START.search(eventos or '')
    if not m:
        return []
    t = m.group(1).replace('\r\n', '\n')
    gen = GEN.search(t)
    if gen:
        # del bloque del patrón solo sirve LoadWWPContext (el motor ya lo carga: &WWPContext)
        t = t[:gen.start()] + t[gen.end():]
    t = bloques_plataforma(t)
    t = g.reemplazar_enums(t, enums)
    out = []
    prof = 0
    for l in t.split('\n'):
        s = l.rstrip().replace('\t', '    ')
        if not s.strip():
            if out and out[-1] != '':
                out.append('')
            continue
        codigo = g.sin_comentarios(s).strip()
        if codigo in ('{', '}'):
            continue   # llaves que quedaron de un [web] partido por un comentario
        low = codigo.lower()
        sangria = s[:len(s) - len(s.lstrip())]
        m = PROP_INICIO.match(codigo) if codigo else None
        if m and prof == 0 and m.group(1).lower() in campos and a_reglas is not None:
            expr = g.sin_comentarios(m.group(3)).strip()
            if re.fullmatch(r'(?i)true|false', expr):
                a_reglas.append(f'{m.group(1)}.{m.group(2)} = {expr.lower()};')
                out.append(sangria + '// (pasó a reglas) ' + s.strip())
            else:
                # la condición se "fotografía" en este punto del Start (las &variables se reusan más abajo)
                var = f'{m.group(2).capitalize()}{m.group(1)}'
                a_reglas.append(f'{m.group(1)}.{m.group(2)} = &{var};')
                out.append(sangria + f'&{var} = {expr}    // pasó a reglas: {m.group(1)}.{m.group(2)}')
                if a_reglas is not None:
                    FOTOS.append(var)
        elif codigo and INICIO_NO.match(codigo):
            out.append(sangria + '// REVISAR (de la pantalla de GeneXus): ' + s.strip())
            continue
        else:
            out.append(s)
        if re.match(r'(?i)^(if\b|for\b|do\s+while\b|do\s+case\b)', low):
            prof += 1
        elif re.match(r'(?i)^(endif|end if|endfor|end for|enddo|end do|endcase|end case)\b', low):
            prof = max(0, prof - 1)
    while out and out[-1] == '':
        out.pop()
    while out and out[0] == '':
        out.pop(0)
    # sangría mínima
    ind = min((len(x) - len(x.lstrip()) for x in out if x.strip()), default=0)
    return [x[ind:] if x.strip() else '' for x in out]


def variables_usadas(textos):
    r = []
    for t in textos:
        for m in re.finditer(r'&([A-Za-z_]\w*)', g.sin_comentarios(t)):
            n = m.group(1)
            if n.lower() not in [x.lower() for x in r]:
                r.append(n)
    return r


def bloque_variables(nombres, defs, kb):
    por = {d['nombre'].lower(): d for d in defs}
    out = []
    for n in nombres:
        d = por.get(n.lower())
        if d is None or n.lower() in ('mode', 'pgmname', 'pgmdesc'):
            continue
        t = gp.tipo_de(d['props'], kb) or 'Ext(Desconocido)'
        out.append((d['nombre'], t))
    if not out:
        return []
    ancho = max(len(n) for n, _ in out) + 2
    return ['Variables'] + [f'  &{n.ljust(ancho)}{t}' for n, t in out] + ['EndVariables']


def procs_llamados(textos, procs):
    nombres = {k.lower(): k for k in procs}
    r = set()
    for t in textos:
        c = g.sin_comentarios(t)
        for m in re.finditer(r'(?i)\b([A-Za-z_]\w*)\s*\.\s*(?:call|udp)\s*\(', c):
            if m.group(1).lower() in nombres:
                r.add(nombres[m.group(1).lower()])
        for m in re.finditer(r'(?<![\w.&])([A-Za-z_]\w*)\s*\(', c):
            if m.group(1).lower() in nombres:
                r.add(nombres[m.group(1).lower()])
    return r


def cerrar_procs(semillas, procs):
    vistos, pend = set(), list(semillas)
    while pend:
        n = pend.pop()
        if n in vistos or n not in procs:
            continue
        vistos.add(n)
        pend += list(procs_llamados([procs[n]['partes'].get(gp.P_SOURCE, '') or ''], procs) - vistos)
    return vistos


# ----------------------------------------------------------------------------- YAML

def bloque_yaml(clave, lineas):
    return [f'{clave}: |'] + ['  ' + l if l else '' for l in lineas]


def insertar(texto, inicio, reglas):
    ls = texto.split('\n')
    # el comentario PENDIENTE (encabezado + reglas listadas) se va: ahora están en 'reglas:'
    i = next((k for k, l in enumerate(ls) if l.startswith('# ---') and 'PENDIENTE' in l), None)
    if i is not None:
        j = i + 1
        while j < len(ls) and (ls[j].startswith('#   ') or ls[j].startswith('# Reglas de GeneXus que el motor')):
            j += 1
        del ls[i:j]
        donde = i
    else:
        donde = len(ls)
        while donde > 0 and (ls[donde - 1].startswith('#') or ls[donde - 1] == ''):
            donde -= 1
    nuevo = []
    if inicio:
        nuevo += bloque_yaml('inicio', inicio)
    if reglas:
        nuevo += bloque_yaml('reglas', reglas)
    if nuevo:
        if donde > 0 and ls[donde - 1] != '':
            nuevo = [''] + nuevo
        ls[donde:donde] = nuevo + ['']
    t = '\n'.join(ls)
    return re.sub(r'\n{3,}', '\n\n', t)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('xml')
    ap.add_argument('--trn', required=True)
    ap.add_argument('--proc', required=True)
    ap.add_argument('--solo', default='')
    ap.add_argument('--ver', action='store_true')
    ap.add_argument('--pisar', action='store_true')
    a = ap.parse_args()
    kb = pf.cargar_kb(a.xml)
    M = g._modelo(kb)
    enums = g.enumerados(kb)
    vars_trn = variables_trn(a.xml)
    procs = gp.leer_procs(a.xml)
    globales = os.path.join(os.path.dirname(os.path.abspath(a.trn)), 'dominios.yaml')
    if os.path.exists(globales):
        pf.GLOBALES.update(str(k) for k in ((yaml.safe_load(open(globales, encoding='utf-8')) or {}).get('dominios') or {}))
    solo = {x.strip().lower() for x in a.solo.split(',') if x.strip()}
    necesitan = set()
    total = 0
    for archivo in sorted(os.listdir(a.trn)):
        if not archivo.endswith('.yaml'):
            continue
        ruta = os.path.join(a.trn, archivo)
        texto = open(ruta, encoding='utf-8').read()
        m = re.search(r'^transaccion:\s*(\S+)', texto, re.M)
        if not m or (solo and m.group(1).lower() not in solo):
            continue
        n = m.group(1)
        if re.search(r'^reglas:', texto, re.M) and not a.pisar:
            continue
        obj = kb.get('objetivos', {}).get(n)
        if not obj:
            continue
        doc = yaml.safe_load(texto) or {}
        campos = {str(c.get('nombre')).lower() for c in (doc.get('campos') or []) if isinstance(c, dict)}
        for d in doc.get('detalles') or []:
            campos |= {str(c.get('nombre')).lower() for c in (d.get('campos') or []) if isinstance(c, dict)}
        reglas = reglas_de(obj.get('reglas') or '', campos, enums)
        del_inicio = []
        inicio = inicio_de(obj.get('eventos') or '', enums, campos, del_inicio)
        if del_inicio:
            reglas += ['', '// Del evento Start (Visible/Enabled que dependen de parámetros)'] + [g.reemplazar_enums(x, enums) for x in del_inicio]
        if not reglas and not inicio:
            continue
        # variables (tipos) al principio del inicio
        vs = variables_usadas(reglas + inicio)
        decl = bloque_variables(vs, vars_trn.get(n, []) + [{'nombre': f, 'props': {'ATTCUSTOMTYPE': 'bas:Boolean'}} for f in FOTOS], kb)
        FOTOS.clear()
        if decl:
            inicio = decl + ([''] if inicio else []) + inicio
        # atributos que usan las reglas y faltan en el YAML
        usados = set()
        for l in reglas + inicio:
            for x in re.finditer(r'(?<![&\w.])([A-Za-z_]\w*)(?![\w(])', re.sub(r'"[^"]*"|\'[^\']*\'', '', g.sin_comentarios(l))):
                if x.group(1) in kb['attrs']:
                    usados.add(x.group(1))
        cambios = []
        nuevo = texto
        try:
            generado = g.generar(kb, n, set(), extra=usados)
            nuevo, cambios = pf.parchar(texto, generado, M, kb)
        except Exception as e:
            cambios.append(f'REVISAR: no se pudieron agregar los atributos que usan las reglas ({type(e).__name__}: {e})')
        nuevo = insertar(nuevo, inicio, reglas)
        necesitan |= procs_llamados(reglas + inicio, procs)
        total += 1
        print(f'== {archivo}: {sum(1 for l in reglas if l.endswith(";"))} reglas, inicio de {len(inicio)} renglones' + (f', {len(cambios)} cambios de campos' if cambios else ''))
        if not a.ver:
            open(ruta, 'w', encoding='utf-8').write(nuevo)
    # procedimientos que llaman las reglas y el inicio
    todos = cerrar_procs(necesitan, procs)
    existentes = {f[:-5].lower() for f in os.listdir(a.proc) if f.endswith('.proc')} if os.path.isdir(a.proc) else set()
    faltan = sorted(p for p in todos if p.lower() not in existentes and p not in ('LoadWWPContext', 'SetWWPContext', 'GetWWPContext'))
    print(f'{total} TRN con reglas; procedimientos que usan: {len(todos)}, faltan en proc/: {len(faltan)}')
    if faltan and not a.ver:
        os.makedirs(a.proc, exist_ok=True)
        for p in faltan:
            txt, _ = gp.armar(p, procs[p], kb, enums)
            open(os.path.join(a.proc, p + '.proc'), 'w', encoding='utf-8').write(txt)
        open(os.path.join(a.proc, '_nuevos.txt'), 'w', encoding='utf-8').write('\n'.join(faltan) + '\n')


if __name__ == '__main__':
    main()
